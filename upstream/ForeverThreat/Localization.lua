FT.locales = {
    DE = DE,
    EN = EN,
    ES = ES,
    FR = FR,
    KO = KO,
    RU = RU,
}

function FT:GetLanguage()
    local lang = self.db and self.db.language or self.defaultLanguage or "EN"
    if lang ~= "DE" and lang ~= "EN" and lang ~= "ES" and lang ~= "FR" and lang ~= "KO" and lang ~= "RU" then
        lang = self.defaultLanguage or "EN"
    end
    return lang
end

function FT:L(key, ...)
    local lang = self:GetLanguage()
    local tableForLanguage = self.locales[lang] or EN
    local text = tableForLanguage[key] or EN[key] or DE[key] or key

    if select("#", ...) > 0 then
        local ok, formatted = pcall(string.format, text, ...)
        if ok then
            return formatted
        end
    end

    return text
end

function FT:SetLanguage(language, silent)
    local lang = tostring(language or ""):upper()

    if lang == "DEDE" or lang == "GERMAN" then
        lang = "DE"
    elseif lang == "ENUS" or lang == "ENGB" or lang == "ENGLISH" then
        lang = "EN"
    elseif lang == "ESES" or lang == "ESMX" or lang == "SPANISH" or lang == "ESPANOL" or lang == "ESPAÑOL" then
        lang = "ES"
    elseif lang == "FRFR" or lang == "FRENCH" or lang == "FRANCAIS" or lang == "FRANÇAIS" then
        lang = "FR"
    elseif lang == "KOKR" or lang == "KOREAN" or lang == "한국어" then
        lang = "KO"
    elseif lang == "RURU" or lang == "RUSSIAN" or lang == "РУССКИЙ" then
        lang = "RU"
    end

    if lang ~= "DE" and lang ~= "EN" and lang ~= "ES" and lang ~= "FR" and lang ~= "KO" and lang ~= "RU" then
        return false
    end

    if self.db then
        self.db.language = lang
    end

    if self.RefreshConfigLocale then
        self:RefreshConfigLocale()
    end

    if self.RefreshSupportLocale then
        self:RefreshSupportLocale()
    end

    if self.RefreshConfigControls then
        self:RefreshConfigControls()
    end

    if self.RefreshCombatWarningLocale then
        self:RefreshCombatWarningLocale()
    end

    if self.RefreshBlizzardSettingsLocale then
        self:RefreshBlizzardSettingsLocale()
    end

    if self.RefreshClickToTauntButton then
        self:RefreshClickToTauntButton()
    end

    if self.Refresh then
        self:Refresh()
    end

    if not silent then
        self:Print(self:L("LANGUAGE_CHANGED"))
    end

    return true
end
