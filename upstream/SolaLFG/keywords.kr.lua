-- Season of Discovery raid entries
if C_Seasons and C_Seasons.GetActiveSeason and C_Seasons.GetActiveSeason() == 2 then
	local raidCat, dungeonCat
	for _, cat in ipairs(FP_DUNGEON_KEYWORDS) do
		if cat.category == "공격대" then
			raidCat = cat
		elseif cat.category == "던전" then
			dungeonCat = cat
		end
	end

	if raidCat and dungeonCat then
		table.insert(raidCat.dungeon, {
			name = "검은심연의 나락",
			color = "raid10",
			keywords = {"심연", "검은심연"},
			excludekeywords = {"바위", "심연의홀", "홀"},
		})
		for i, d in ipairs(dungeonCat.dungeon) do
			if d.name == "검은심연의 나락" then
				table.remove(dungeonCat.dungeon, i)
				break
			end
		end

		table.insert(raidCat.dungeon, {
			name = "놈리건",
			color = "raid10",
			keywords = {"놈리건"},
		})
		for i, d in ipairs(dungeonCat.dungeon) do
			if d.name == "놈리건" then
				table.remove(dungeonCat.dungeon, i)
				break
			end
		end
	end
end

